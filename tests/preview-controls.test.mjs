import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {bindPreviewControls} from '../web/preview-controls.mjs';

test('preview controls debounce activity without sticking on hover, hold only while interacting',t=>{
 t.mock.timers.enable({apis:['setTimeout']});
 const dom=new JSDOM('<section id="viewer"><div id="viewer-content" tabindex="0"></div><div id="zone"><button>Play</button><div role="slider" tabindex="0"></div></div></section>');
 const doc=dom.window.document;
 const [viewer,zone]=['viewer','zone'].map(id=>doc.getElementById(id));
 const controls=bindPreviewControls(viewer,zone);
 let x=0;
 const event=(target,type)=>target.dispatchEvent(type==='pointermove'?new dom.window.MouseEvent(type,{bubbles:true,clientX:++x,clientY:100}):new dom.window.Event(type,{bubbles:true}));
 controls.setActive(true);
 t.mock.timers.tick(1600);
 assert.equal(zone.dataset.visible,'false','entry alone must hide after the initial delay');
 controls.setActive(true);
 const stationary=()=>viewer.dispatchEvent(new dom.window.MouseEvent('pointermove',{bubbles:true,clientX:100,clientY:100}));
 stationary();
 for(let i=0;i<4;i++){t.mock.timers.tick(400);stationary();}
 assert.equal(zone.dataset.visible,'false','stationary pointer events must not keep controls visible');
 controls.setActive(true);
 t.mock.timers.tick(1200);
 event(viewer,'pointermove');
 t.mock.timers.tick(1200);
 assert.equal(zone.dataset.visible,'true');
 t.mock.timers.tick(400);
 assert.equal(zone.dataset.visible,'false');
 assert.equal(zone.inert,true);
 event(viewer,'pointermove');
 event(zone,'pointerenter');
 t.mock.timers.tick(5000);
 assert.equal(zone.dataset.visible,'false');
 event(viewer,'pointermove');
 event(zone.querySelector('[role="slider"]'),'pointerdown');
 t.mock.timers.tick(5000);
 assert.equal(zone.dataset.visible,'true');
 event(doc,'pointerup');
 t.mock.timers.tick(1600);
 assert.equal(zone.dataset.visible,'false');
 event(viewer,'pointermove');
 doc.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Tab',bubbles:true}));
 zone.querySelector('button').focus();
 t.mock.timers.tick(5000);
 assert.equal(zone.dataset.visible,'true');
 event(viewer,'pointermove');
 t.mock.timers.tick(1600);
 assert.equal(zone.dataset.visible,'false');
 controls.setActive(false);
 event(viewer,'pointermove');
 assert.equal(zone.dataset.visible,'false');
 controls.dispose();
 dom.window.close();
});
